// ELEMEN WEBSITE
const searchInput = document.getElementById("searchInput");
const bookContainer = document.getElementById("bookContainer");
const reader = document.getElementById("reader");


// MENAMPILKAN SEMUA CERPEN
function tampilkanCerpen(data) {

    bookContainer.innerHTML = "";

    if (data.length === 0) {
        bookContainer.innerHTML = `
            <div class="no-result">
                <h3>Cerita tidak ditemukan</h3>
                <p>Silakan cari judul lainnya.</p>
            </div>
        `;
        return;
    }

    data.forEach(function(cerita) {

        const card = document.createElement("div");
        card.className = "book-card";

        const cover = document.createElement("div");
        cover.className = "book-cover";
        cover.textContent = "📖";

        const info = document.createElement("div");
        info.className = "book-info";

        const kategori = document.createElement("small");
        kategori.textContent = cerita.kategori;

        const judul = document.createElement("h3");
        judul.textContent = cerita.judul;

        const deskripsi = document.createElement("p");
        deskripsi.textContent =
            cerita.isi.substring(0, 95) + "...";

        const tombol = document.createElement("button");
        tombol.textContent = "Baca Cerita →";

        tombol.addEventListener("click", function() {
            bacaCerpen(cerita.id);
        });

        info.append(kategori, judul, deskripsi, tombol);
        card.append(cover, info);

        bookContainer.appendChild(card);

    });

}


// FITUR PENCARIAN
searchInput.addEventListener("input", function() {

    const keyword = searchInput.value.toLowerCase();

    const hasil = daftarCerpen.filter(function(cerita) {

        return (
            cerita.judul.toLowerCase().includes(keyword) ||
            cerita.kategori.toLowerCase().includes(keyword)
        );

    });

    tampilkanCerpen(hasil);

});


// BUKA CERPEN
function bacaCerpen(id) {

    const cerita = daftarCerpen.find(function(item) {
        return item.id === id;
    });

    if (!cerita) return;

    document.getElementById("judulCerpen").textContent =
        cerita.judul;

    document.getElementById("isiCerpen").textContent =
        cerita.isi;

    reader.style.display = "block";

    reader.scrollIntoView({
        behavior: "smooth"
    });

}


// TUTUP CERPEN
function tutupCerpen() {

    reader.style.display = "none";

    document.getElementById("cerpen").scrollIntoView({
        behavior: "smooth"
    });

}


// TAHUN OTOMATIS
const teksTahun = document.querySelector("footer p:last-child");

if (teksTahun) {
    teksTahun.textContent =
        "© " + new Date().getFullYear() +
        " Rasya Rafi Ardiansyah. All Rights Reserved.";
}


// JALANKAN WEBSITE
tampilkanCerpen(daftarCerpen);

